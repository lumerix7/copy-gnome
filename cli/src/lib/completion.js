export function commandNames() {
  return COMMANDS.map(c => c.name);
}

export function generateCompletion(shell) {
  if (shell !== "bash")
    throw new Error(`unsupported shell for completion: ${shell} (supported: bash)`);
  return bashCompletion();
}

function bashCompletion() {
  const commandWords = commandNames().join(" ");
  const configSubcommands = Object.keys(COMMANDS.find(c => c.name === "config").subcommands).join(" ");
  const configKeyWords = CONFIG_KEYS.join(" ");
  const globalWords = GLOBAL_OPTIONS.join(" ");
  const lines = [];

  lines.push("# bash completion for copy-gnome - generated by: copy-gnome --completion bash");
  lines.push("# install: copy-gnome --completion bash > ~/.local/share/bash-completion/completions/copy-gnome");
  lines.push("_copy_gnome_complete() {");
  lines.push("  local cur prev cmd subcmd words config_keys");
  lines.push("  COMPREPLY=()");
  lines.push("  cur=\"${COMP_WORDS[COMP_CWORD]}\"");
  lines.push("  prev=\"${COMP_WORDS[COMP_CWORD-1]}\"");
  lines.push(`  words="${commandWords}"`);
  lines.push(`  config_keys="${configKeyWords}"`);
  lines.push("");
  lines.push("  for ((i=1; i<COMP_CWORD; i++)); do");
  lines.push("    case \"${COMP_WORDS[i]}\" in");
  lines.push(`      ${commandNames().join("|")}) cmd="\${COMP_WORDS[i]}"; break ;;`);
  lines.push("    esac");
  lines.push("  done");
  lines.push("  if [[ \"$cmd\" == \"config\" ]]; then");
  lines.push("    for ((i=2; i<COMP_CWORD; i++)); do");
  lines.push("      case \"${COMP_WORDS[i]}\" in");
  lines.push("        path|validate|show|get|set|edit) subcmd=\"${COMP_WORDS[i]}\"; break ;;");
  lines.push("      esac");
  lines.push("    done");
  lines.push("  fi");
  lines.push("");
  lines.push("  case \"$prev\" in");
  lines.push("    --completion)");
  lines.push("      COMPREPLY=( $(compgen -W \"bash\" -- \"$cur\") )");
  lines.push("      return ;;");

  for (const [flag, spec] of valueSpecs()) {
    lines.push(`    ${escapeCase(flag)})`);
    if (spec.kind === "file") {
        lines.push("      COMPREPLY=( $(compgen -f -- \"$cur\") )");
    } else if (spec.kind === "choice") {
        lines.push(`      COMPREPLY=( $(compgen -W "${spec.words.join(" ")}" -- "$cur") )`);
    } else {
        lines.push("      COMPREPLY=()");
    }
    lines.push("      return ;;");
  }

  lines.push("  esac");
  lines.push("");
  lines.push("  if [[ -z \"$cmd\" ]]; then");
  lines.push("    if [[ \"$cur\" == -* ]]; then");
  lines.push(`      COMPREPLY=( $(compgen -W "${globalWords}" -- "$cur") )`);
  lines.push("    else");
  lines.push("      COMPREPLY=( $(compgen -W \"$words\" -- \"$cur\") )");
  lines.push("    fi");
  lines.push("    return");
  lines.push("  fi");
  lines.push("");
  lines.push("  if [[ \"$cur\" == -* ]]; then");
  lines.push("    case \"$cmd\" in");
  for (const command of COMMANDS) {
    if (command.subcommands) {
      lines.push(`      ${escapeCase(command.name)})`);
      lines.push("        case \"$subcmd\" in");
      for (const [subcmd, spec] of Object.entries(command.subcommands))
        lines.push(`          ${escapeCase(subcmd)}) COMPREPLY=( $(compgen -W "${spec.options.join(" ")}" -- "$cur") ) ;;`);
      lines.push(`          *) COMPREPLY=( $(compgen -W "${command.options.join(" ")}" -- "$cur") ) ;;`);
      lines.push("        esac ;;");
      continue;
    }
    lines.push(`      ${escapeCase(command.name)}) COMPREPLY=( $(compgen -W "${command.options.join(" ")}" -- "$cur") ) ;;`);
  }
  lines.push("    esac");
  lines.push("    return");
  lines.push("  fi");
  lines.push("");
  lines.push("  if [[ \"$cmd\" == \"config\" && -z \"$subcmd\" ]]; then");
  lines.push(`    COMPREPLY=( $(compgen -W "${configSubcommands}" -- "$cur") )`);
  lines.push("    return");
  lines.push("  fi");
  lines.push("");
  lines.push("  if [[ \"$cmd\" == \"config\" && \"$subcmd\" == \"get\" ]]; then");
  lines.push("    COMPREPLY=( $(compgen -W \"$config_keys\" -- \"$cur\") )");
  lines.push("    return");
  lines.push("  fi");
  lines.push("");
  lines.push("  if [[ \"$cmd\" == \"config\" && \"$subcmd\" == \"set\" && $COMP_CWORD -le 3 ]]; then");
  lines.push("    COMPREPLY=( $(compgen -W \"$config_keys\" -- \"$cur\") )");
  lines.push("    return");
  lines.push("  fi");
  lines.push("}");
  lines.push("complete -F _copy_gnome_complete copy-gnome");
  lines.push("");

  return lines.join("\n");
}

function escapeCase(value) {
  return String(value).replace(/([\\|)])/g, "\\$1");
}

function valueSpecs() {
  const map = new Map();
  for (const command of COMMANDS) {
    for (const [flag, spec] of Object.entries(command.values || {}))
      map.set(flag, spec);
    for (const subcommand of Object.values(command.subcommands || {})) {
      for (const [flag, spec] of Object.entries(subcommand.values || {}))
        map.set(flag, spec);
    }
  }
  return map.entries();
}
